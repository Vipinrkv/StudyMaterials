def extended_gcd(a: int, b: int) -> Tuple[int, int, int]:
    """Returns (gcd, x, y) such that a*x + b*y = gcd."""
    if a == 0:
        return b, 0, 1
    gcd, x1, y1 = extended_gcd(b % a, a)
    x = y1 - (b // a) * x1
    y = x1
    return gcd, x, y


def mod_inverse(a: int, m: int) -> int:
    """Computes modular multiplicative inverse a^-1 mod m."""
    gcd, x, _ = extended_gcd(a % m, m)
    if gcd != 1:
        raise ValueError(f"Modular inverse does not exist for {a} mod {m}")
    return (x % m + m) % m


class ECPoint:
    """Point on Weierstrass curve y^2 = x^3 + a*x + b (mod p)."""
    def __init__(self, x: Optional[int], y: Optional[int], is_infinity: bool = False):
        self.x = x
        self.y = y
        self.is_infinity = is_infinity

    def __repr__(self):
        if self.is_infinity:
            return "Point(Infinity)"
        return f"Point({self.x}, {self.y})"

    def __eq__(self, other: 'ECPoint') -> bool:
        if self.is_infinity and other.is_infinity:
            return True
        return self.x == other.x and self.y == other.y and self.is_infinity == other.is_infinity


class EllipticCurve:
    """Weierstrass Elliptic Curve over prime finite field F_p."""
    def __init__(self, p: int, a: int, b: int, g_x: int, g_y: int, n: int):
        self.p = p  # Field prime
        self.a = a  # Curve parameter a
        self.b = b  # Curve parameter b
        self.G = ECPoint(g_x, g_y)  # Generator base point
        self.n = n  # Order of subgroup generated by G

    def is_on_curve(self, pt: ECPoint) -> bool:
        if pt.is_infinity:
            return True
        lhs = (pt.y * pt.y) % self.p
        rhs = (pt.x ** 3 + self.a * pt.x + self.b) % self.p
        return lhs == rhs

    def point_add(self, p1: ECPoint, p2: ECPoint) -> ECPoint:
        if p1.is_infinity:
            return p2
        if p2.is_infinity:
            return p1
        if p1.x == p2.x and (p1.y != p2.y or p1.y == 0):
            return ECPoint(None, None, is_infinity=True)

        if p1 == p2:
            # Point Doubling: lambda = (3*x1^2 + a) / (2*y1) mod p
            num = (3 * p1.x * p1.x + self.a) % self.p
            den = (2 * p1.y) % self.p
        else:
            # Point Addition: lambda = (y2 - y1) / (x2 - x1) mod p
            num = (p2.y - p1.y) % self.p
            den = (p2.x - p1.x) % self.p

        lam = (num * mod_inverse(den, self.p)) % self.p
        x3 = (lam * lam - p1.x - p2.x) % self.p
        y3 = (lam * (p1.x - x3) - p1.y) % self.p
        return ECPoint(x3, y3)

    def scalar_mult(self, k: int, pt: ECPoint) -> ECPoint:
        """Double-and-Add scalar multiplication k * P."""
        result = ECPoint(None, None, is_infinity=True)
        current = pt
        k = k % self.n
        while k > 0:
            if k & 1:
                result = self.point_add(result, current)
            current = self.point_add(current, current)
            k >>= 1
        return result


