class SchnorrZKP:
    """
    Non-Interactive Schnorr Proof of Knowledge of Discrete Logarithm:
    Proves knowledge of secret x such that Y = g^x (mod p) without revealing x.
    """
    def __init__(self, p: int, g: int, q: Optional[int] = None):
        self.p = p  # Large prime field
        self.g = g  # Generator
        self.q = q if q is not None else (p - 1)  # Subgroup order (default p - 1)

    def prove(self, secret_x: int, random_r: int) -> Tuple[int, int]:
        """
        Commitment: T = g^r mod p
        Challenge:  c = H(g || Y || T) mod q
        Response:   s = r + c * x mod q
        Returns proof tuple (T, s).
        """
        y = pow(self.g, secret_x, self.p)
        t = pow(self.g, random_r, self.p)
        
        # Fiat-Shamir hash challenge
        c_bytes = hashlib.sha256(f"{self.g}:{y}:{t}".encode("utf-8")).digest()
        c = int.from_bytes(c_bytes, "big") % self.q
        
        s = (random_r + c * secret_x) % self.q
        return t, s

    def verify(self, public_y: int, proof: Tuple[int, int]) -> bool:
        """
        Verifies: g^s == T * Y^c (mod p)
        """
        t, s = proof
        c_bytes = hashlib.sha256(f"{self.g}:{public_y}:{t}".encode("utf-8")).digest()
        c = int.from_bytes(c_bytes, "big") % self.q
        
        lhs = pow(self.g, s, self.p)
        rhs = (t * pow(public_y, c, self.p)) % self.p
        return lhs == rhs


