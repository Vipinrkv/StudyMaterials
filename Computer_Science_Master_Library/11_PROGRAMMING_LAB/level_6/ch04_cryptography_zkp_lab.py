class ECDSASystem:
    def __init__(self, curve: EllipticCurve):
        self.curve = curve

    def generate_keypair(self, private_key: int) -> Tuple[int, ECPoint]:
        public_key = self.curve.scalar_mult(private_key, self.curve.G)
        return private_key, public_key

    def sign(self, private_key: int, msg_hash: int, nonce_k: int) -> Tuple[int, int]:
        """ECDSA signature generation: (r, s)."""
        r_point = self.curve.scalar_mult(nonce_k, self.curve.G)
        r = r_point.x % self.curve.n
        if r == 0:
            raise ValueError("Invalid nonce: r == 0")
        
        # s = k^-1 * (z + r * d) mod n
        k_inv = mod_inverse(nonce_k, self.curve.n)
        s = (k_inv * (msg_hash + r * private_key)) % self.curve.n
        if s == 0:
            raise ValueError("Invalid nonce: s == 0")
        return r, s

    def verify(self, public_key: ECPoint, msg_hash: int, r: int, s: int) -> bool:
        """ECDSA signature verification."""
        if not (1 <= r < self.curve.n and 1 <= s < self.curve.n):
            return False
        w = mod_inverse(s, self.curve.n)
        u1 = (msg_hash * w) % self.curve.n
        u2 = (r * w) % self.curve.n
        
        # P = u1 * G + u2 * Q
        p1 = self.curve.scalar_mult(u1, self.curve.G)
        p2 = self.curve.scalar_mult(u2, public_key)
        p = self.curve.point_add(p1, p2)
        
        if p.is_infinity:
            return False
        return (p.x % self.curve.n) == r

    @staticmethod
    def extract_private_key_on_nonce_reuse(
        msg_hash1: int, s1: int,
        msg_hash2: int, s2: int,
        r: int, curve_n: int
    ) -> Tuple[int, int]:
        """
        The Sony PS3 Exploit:
        Recovers nonce k and private key d from two signatures that reused k.
        k = (z1 - z2) / (s1 - s2) mod n
        d = (s1 * k - z1) / r mod n
        """
        s_diff = (s1 - s2) % curve_n
        z_diff = (msg_hash1 - msg_hash2) % curve_n
        k = (z_diff * mod_inverse(s_diff, curve_n)) % curve_n
        
        d = ((s1 * k - msg_hash1) * mod_inverse(r, curve_n)) % curve_n
        return k, d


